from typing import Any, Iterable


def _normalize_boards(values: Iterable[str]) -> list[str]:
    ordered: list[str] = []
    for value in values:
        cleaned = str(value or "").strip().lower()
        if cleaned and cleaned not in ordered:
            ordered.append(cleaned)
    return ordered


