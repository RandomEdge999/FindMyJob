def bootstrap_board_targets() -> dict[str, list[str]]:
    return {
        source_name: list(boards)
        for source_name, boards in BOOTSTRAP_PORTAL_BOARDS.items()
    }


def default_portal_sources_payload() -> dict[str, dict[str, Any]]:
    return {
        source_name: (
            {
                "enabled": True,
                "boards": [],
                "seed_urls": [],
                "seed_domains": [],
            }
            if source_name == "greenhouse"
            else {
                "enabled": False,
                "boards": [],
                "seed_urls": [],
                "seed_domains": [],
            }
        )
        for source_name in BOOTSTRAP_PORTAL_BOARDS
    }


def default_portals_payload() -> dict[str, Any]:
    return {
        "sources": default_portal_sources_payload(),
        "tracked_companies": [],
    }
